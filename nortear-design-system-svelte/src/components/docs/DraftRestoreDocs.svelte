        <DraftRestore
          labels={draftLabels}
          draft={SAMPLE_DRAFT}
          timestamp={SAMPLE_TIMESTAMP}
        />
      </div>

      <Separator />

      <div class="nds-stack nds-w-full" data-spacing="xs">
        <p class="nds-text-caption nds-text-muted-foreground">
          {$tStore('demonstration.labels.long')}
        </p>
        <DraftRestore
          labels={draftLabels}
          draft={SAMPLE_DRAFT_LONG}
          timestamp={SAMPLE_TIMESTAMP}
        />
      </div>

      <Separator />

      <!--
        A faixa onde ela de fato mora: acima do campo, e fora dele. Sem
        utilitário de pilha — a distância até o campo já é do desenho da faixa,
        e uma pilha por cima somaria o gap dela ao respiro da folha.
      -->
      <div class="nds-stack nds-w-full" data-spacing="xs">
        <p class="nds-text-caption nds-text-muted-foreground">
          {$tStore('demonstration.labels.aboveComposer')}
        </p>
        <div class="nds-w-full">
          <DraftRestore
            labels={draftLabels}
            draft={SAMPLE_DRAFT}
            timestamp={SAMPLE_TIMESTAMP}
          />
          <Composer {labels} />
        </div>
      </div>
    </div>
  </DocsDemonstration>

  <!-- ── Anatomia ───────────────────────────────────────────────── -->
  <DocsAnatomy
    title={$tStore('anatomy.title')}
    items={[1, 2, 3, 4, 5].map(i => $tStore(`anatomy.item${i}`))}
    structureLabel={$tStore('anatomy.structureLabel')}
    structureCode={$tStore('anatomy.structureCode')}
    language="html"
  />

  <!-- ── Quando Usar ────────────────────────────────────────────── -->
  <DocsWhenToUse
    title={$tStore('usage.title')}
    guidelines={{
      title: $tStore('usage.guidelines.title'),
      items: [1, 2, 3, 4, 5].map(i => $tStore(`usage.guidelines.item${i}`)),
