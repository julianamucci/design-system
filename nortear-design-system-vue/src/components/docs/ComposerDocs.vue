    code: tContent(`variants.items.${mode}.code`),
  })),
);

const stateItems = computed(() =>
  ['empty', 'filled', 'running', 'nearLimit', 'disabled'].map(k => ({
    label: tContent(`states.${k}.label`),
    trigger: toPlainText(tContent(`states.${k}.trigger`)),
    behavior: toPlainText(tContent(`states.${k}.behavior`)),
  })),
);

const propsTables = computed(() => [
  {
    title: 'Composer',
    cols: {
      prop: tContent('props.table.prop'),
      type: tContent('props.table.type'),
      default: tContent('props.table.default'),
      required: tContent('props.table.required'),
      description: tContent('props.table.description'),
    },
    items: [
      'labels', 'value', 'rows', 'maxLength', 'submitOn',
      'running', 'disabled', 'railStart', 'onSubmit', 'onStop', 'class',
    ].map(k => ({
      name: tContent(`props.table.${k}.name`),
      type: tContent(`props.table.${k}.type`),
      defaultValue: tContent(`props.table.${k}.default`),
      required: tContent(`props.table.${k}.required`),
      description: toPlainText(tContent(`props.table.${k}.description`)),
    })),
  },
]);

const interfaceCode = `// Composer.vue
interface ComposerProps {
  labels: ComposerLabels;
  value?: string;
  rows?: number;
  maxLength?: number;
  submitOn?: 'enter' | 'modifier';
  running?: boolean;
  disabled?: boolean;
  class?: string;
}

// O TEXTO é um vínculo, e não um método: \`v-model:value\`. Sem ninguém do lado
// de fora ele é estado local; com o vínculo, é por ali que um rascunho volta.
// O estado de geração é a prop \`running\` — quem sabe é quem consome.

// O que sai do componente:
//   @submit — o texto pedido, sem espaços nas pontas
//   @stop   — alguém pediu para interromper a geração

// A marcação que quem consome fornece entra por SLOT:
//   <template #railStart> — os controles do início do trilho`;

const tokenItems = computed(() =>
  [
    'background', 'input', 'border', 'ring', 'radius',
    'foreground', 'mutedForeground', 'muted', 'destructive',
